import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source=readFileSync('src/letsaigc/ui_analysis/review_web/state.js','utf8');
const {snapGeometry:snap,defaultSnapOptions,snapReferences}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const ref=(id,bbox)=>({id,bbox});
const options=(values={})=>({...defaultSnapOptions(),...values});
const only=key=>options({edges:false,centers:false,canvas:false,spacing:false,[key]:true});
const run=(box,extra={})=>snap({kind:'move',box,width:1000,height:1000,references:[ref('a',[100,100,120,120])],options:only('edges'),...extra});
assert.deepEqual(run([75,75,95,95]).box,[80,80,100,100]);
assert.deepEqual(run([75,75,95,95],{options:options({enabled:false})}).box,[75,75,95,95]);
assert.deepEqual(run([75,75,95,95],{scale:[2,2]}).box,[75,75,95,95]);
const first=run([76,200,96,220]);
assert.equal(run([72,200,92,220],{previous:first.hits}).box[2],100);
assert.equal(run([69,200,89,220],{previous:first.hits}).box[2],89);
assert.equal(run([99,200,120,220],{options:only('centers')}).hits[0],null);
assert.equal(run([98,200,118,220],{options:only('centers')}).box[0],100);
assert.deepEqual(run([2,2,22,22],{options:only('canvas')}).box,[0,0,20,20]);
assert.deepEqual(run([0,100,30,120],{references:[ref('r',[10,100,15,120])],options:only('centers')}).box,[0,100,30,120]);
const pair=[ref('a',[0,100,20,120]),ref('b',[80,100,100,120])];
let g=run([43,100,63,120],{references:pair,options:only('spacing')});
assert.deepEqual(g.box,[40,100,60,120]);assert.equal(g.guides[0].segments[0].distance,20);
const sequence=[ref('a',[20,100,40,120]),ref('b',[60,100,80,120])];
assert.deepEqual(run([103,100,123,120],{references:sequence,options:only('spacing')}).box,[100,100,120,120]);
assert.deepEqual(run([23,100,33,120],{references:[ref('a',[50,100,70,120]),ref('b',[90,100,110,120])],options:only('spacing')}).box,[20,100,30,120]);
assert.equal(run([43,200,63,220],{references:pair,options:only('spacing')}).guides.length,0);
assert.equal(run([43,100,64,120],{references:pair,options:only('spacing')}).guides.length,0);
assert.deepEqual(run([100,43,120,63],{references:pair.map(r=>ref(r.id,[r.bbox[1],r.bbox[0],r.bbox[3],r.bbox[2]])),options:only('spacing')}).box,[100,40,120,60]);
assert.deepEqual(run([40,100,58,120],{kind:'resize',active:[2,3],references:pair,options:only('spacing')}).box,[40,100,60,120]);
assert.deepEqual(run([42,100,60,120],{kind:'resize',active:[0,3],references:pair,options:only('spacing')}).box,[40,100,60,120]);
assert.deepEqual(run([50,50,96,96],{kind:'draw',active:[2,3]}).box,[50,50,100,100]);
assert.deepEqual(run([96,96,150,150],{kind:'resize',active:[0,1]}).box,[100,100,150,150]);
assert.deepEqual(run([98,98,98,98],{kind:'draw',active:[0,1],point:true}).box,[100,100,100,100]);
assert.deepEqual(snapReferences([{element_id:'b',bbox:[1,2,3,4],locked_fields:['bbox']},{element_id:'a',bbox:[4,5,6,7]}],'a'),[ref('b',[1,2,3,4])]);
// Containing background cannot establish a spacing constraint.
assert.deepEqual(run([43,100,63,120],{references:[...pair,ref('background',[0,0,1000,1000])],options:only('spacing')}).box,[40,100,60,120]);
const blocked=[...pair,ref('middle',[25,100,35,120])];
assert.ok(!run([43,100,63,120],{references:blocked,options:only('spacing')}).guides.some(g=>g.ids.join()==='a,b'));
// Deterministic tie order and exact source-independent calculation.
const refs=[ref('z',[80,300,100,320]),ref('a',[100,300,120,320])];
assert.deepEqual(run([78,200,98,220],{references:refs}),run([78,200,98,220],{references:[...refs].reverse()}));
console.log('snap geometry scenarios passed');
